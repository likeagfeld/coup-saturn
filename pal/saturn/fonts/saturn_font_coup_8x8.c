/**
 * saturn_font_coup_8x8.c - Game font in the COUP logo's style.
 *
 * EXTRACTED from the native 8x8 sheet supplied as
 * examples/coup/assets/Official Art/ab8a59e0-*.png - 2048x768, a 16x6 grid of
 * 128x128 cells in ASCII order from space. These are the delivered
 * letterforms read straight off the grid, not reduced from a display face.
 *
 * The sheet is an upscaled render rather than a clean integer blit: horizontal
 * stroke runs measure 13, 14 and 15 px, so there is sub-pixel drift and no
 * single shared grid to sample. Each glyph is therefore located by its own ink
 * bounding box and quantised on ITS OWN grid.
 *
 * The quantum was chosen by MEASUREMENT, not assumption. Sweeping it and
 * counting glyphs that reduce to byte-identical bitmaps:
 *
 *     Q=10  35.3%% ink   1 identical pair (8/B)
 *     Q=11  28.6%% ink   0 identical pairs   <- used
 *     Q=12  23.5%% ink   1 (8/B)
 *     Q=13  21.0%% ink   1 (D/O)
 *     Q=14  18.0%% ink   3 (5/S, 8/B, D/O)
 *
 * A font where two characters render identically is broken regardless of how
 * good it looks, so that count is the criterion.
 *
 * 1bpp, 8 bytes per glyph, 95 glyphs from ASCII 32.
 */

