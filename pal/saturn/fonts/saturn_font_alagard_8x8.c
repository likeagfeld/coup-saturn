/**
 * saturn_font_alagard_8x8.c - Alagard condensed to an 8x8 body face.
 *
 * DERIVED, not redrawn. Generated from s_font_alagard_16x16_1bpp by
 * area-sampling the MEASURED ink extents - columns 2..12 (11 px wide) and
 * rows 1..13 (13 px tall) - down to an 8x8 cell.
 *
 * WHY THIS EXISTS
 *   The 16x16 face cannot be used for body text. Measured: its glyphs carry
 *   ink across 11 columns on an advance of 8, so adjacent letters overlap by
 *   design - fine for a heading where letters interlock, wrong for dense
 *   text. Vertically it needs 13 px (10 for caps alone) against a layout row
 *   pitch of 8, so every line would collide with the one below.
 *
 *   Raising the row pitch to fit it would roughly halve the lines per screen
 *   and force re-paging the rules (83 body lines) and the game log. This
 *   derivative instead drops into the existing 8 px grid with NO layout
 *   change, so the whole game gets the custom face and the 16x16 original
 *   stays for headings, where the overlap is a feature.
 *
 *   Threshold is 1/3 coverage rather than 1/2: a stroke thinner than the
 *   sample box has to survive, or the face dissolves into dots at 8 px.
 *
 * Original: alagard_16x16, CC-BY 3.0, Hewett Tsoi / PIX3M.
 */

